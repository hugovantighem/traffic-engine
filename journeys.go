package engine

import (
	"encoding/json"
	"os"
	"path/filepath"
)

// Journeys is what a user can do in a system, without its deliberate errors: where a journey
// starts, and what each action offers next. It is the contract of a frontend built on the same
// graph as the traffic: one screen per action, the next actions as what the screen offers.
// Action names are the operationIds of the contracts, so a frontend finds the call to make in
// the client generated from the same contracts.
type Journeys struct {
	Starts  []string  `json:"starts"`
	Actions []Journey `json:"actions"`
}

// Journey is one action and the actions that can follow it.
type Journey struct {
	Name string   `json:"name"`
	Next []string `json:"next"`
}

// Journeys keeps what a user can do: the normal entry points, the actions they reach through
// normal links, and those links. Deliberate errors are traffic only: a frontend never offers them.
func (g *Graph) Journeys() Journeys {
	unreachable := map[string]bool{}
	for _, a := range g.Unreachable() {
		unreachable[a] = true
	}
	out := Journeys{Starts: []string{}, Actions: []Journey{}}
	seen := map[string]bool{}
	for _, s := range g.Starts() {
		if s.Fail == "" && !seen[s.Action] {
			seen[s.Action] = true
			out.Starts = append(out.Starts, s.Action)
		}
	}
	for _, n := range g.Nodes() {
		if unreachable[n.Name] {
			continue
		}
		j := Journey{Name: n.Name, Next: []string{}}
		next := map[string]bool{}
		for _, l := range n.Links {
			if l.Fail == "" && !next[l.To] {
				next[l.To] = true
				j.Next = append(j.Next, l.To)
			}
		}
		out.Actions = append(out.Actions, j)
	}
	return out
}

// WriteJourneys writes the journeys of a graph as indented JSON, creating the directory: the file
// a frontend reads (checked in, regenerated by `go generate` or a make target).
func (g *Graph) WriteJourneys(path string) error {
	b, err := json.MarshalIndent(g.Journeys(), "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}
